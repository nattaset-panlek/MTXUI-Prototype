"""Build mtx/js/player-data.js: XP needed for each E / S / R level (source/UltimateFightStatus_Sheets/18_LegacyCoreLevel.csv).

    python -I tools/build_player_data.py <sheets dir> <out js>
"""
import csv
import json
import sys


def column(rows, lv_col, xp_col):
    out = []
    for r in rows[1:]:
        try:
            int(float(r[lv_col]))
            out.append(int(float(r[xp_col])))
        except (ValueError, IndexError):
            break
    return out


if __name__ == "__main__":
    rows = list(csv.reader(open(f"{sys.argv[1]}/18_LegacyCoreLevel.csv", encoding="utf-8-sig")))
    data = {"e": column(rows, 0, 1), "s": column(rows, 6, 7), "r": column(rows, 12, 13)}
    js = ("// Generated by tools/build_player_data.py from 18_LegacyCoreLevel.csv. Do not edit by hand.\n"
          "// xp[track][level - 1] = XP needed to go from that level to the next.\n"
          "window.MTX_PLAYER_DATA = " + json.dumps(data, separators=(",", ":")) + ";\n")
    open(sys.argv[2], "w", encoding="utf-8").write(js)
    print({k: len(v) for k, v in data.items()})
