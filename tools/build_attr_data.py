"""Build mtx/js/attr-data.js from the balancing sheets (source/UltimateFightStatus_Sheets 08/10/12/14/16).

Per style: the 5 attributes with Max Stat / Base Stat / hard cap, the cap after each of the 5 Mastery levels
(base + the "Default Distribution" rows) and every sub-stat with its starting value.

    python -I tools/build_attr_data.py <sheets dir> <out js>
"""
import csv
import json
import sys

SHEETS = [("phranakhon", "08_PhraNakorn.csv"), ("south", "10_Chaiya.csv"), ("isan", "12_Korat.csv"),
          ("north", "14_Tha Sao.csv"), ("west", "16_Lopburi.csv")]
ATTRS = [("attacking", "Attacking"), ("defending", "Defending"), ("striking", "Striking Arts"),
         ("agility", "Agility"), ("endurance", "Endurance")]


def build(sheet_dir):
    out = {}
    for style, name in SHEETS:
        rows = list(csv.reader(open(f"{sheet_dir}/{name}", encoding="utf-8-sig")))
        mx = [float(x) for x in rows[1][2:7]]
        base = [float(x) for x in rows[2][2:7]]
        hard = [float(x) for x in rows[3][2:7]]
        head, start = rows[6], rows[7]
        # the header row is "Base <Attr>", then its sub-stats, then the next "Base <Attr>"
        starts = [i for i, h in enumerate(head) if h.startswith("Base ")]
        attrs = []
        for k, (key, label) in enumerate(ATTRS):
            col = starts[k]
            end = starts[k + 1] if k + 1 < len(starts) else len(head)
            subs = [[head[c], float(start[c])] for c in range(col + 1, end) if head[c] and start[c]]
            caps, cur = [], base[k]
            for r in range(8, 13):
                cur += float(rows[r][col])
                caps.append(round(cur))
            attrs.append({"key": key, "name": label, "max": mx[k], "base": base[k], "hard": hard[k],
                          "caps": caps, "subs": subs})
        out[style] = {"desc": rows[1][1], "attrs": attrs}
    return out


if __name__ == "__main__":
    data = build(sys.argv[1])
    js = ("// Generated by tools/build_attr_data.py from source/UltimateFightStatus_Sheets (08-16). Do not edit by hand.\n"
          "window.MTX_ATTR_DATA = " + json.dumps(data, ensure_ascii=False, indent=1) + ";\n")
    open(sys.argv[2], "w", encoding="utf-8").write(js)
    for s, d in data.items():
        print(s, [(a["key"], a["base"], a["caps"], len(a["subs"]), sum(v for _, v in a["subs"])) for a in d["attrs"]])
