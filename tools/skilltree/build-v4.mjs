// Skill tree v4: one node per Perk (Lv 1-3) instead of three "Tier" nodes.
// In:  tools/skilltree/v3-export.json  (the old Skill-tree_v3 export, 71 nodes)
//      tools/skilltree/perks-wiki.json (per-level EN text from the wiki 10-Skill-Tree-PhraNakorn.md)
// Out: mtx/js/skilltree-data.js        (window.MTX_TREE, 43 nodes)
// Run: node tools/skilltree/build-v4.mjs  (from mtx-controller-flow/)
//
// Layout "B compact": a perk takes its old Tier 1 spot; the node under each perk chain moves up 240,
// and later gates move up with it (gate 4 by 240, gate 5 by 480).
// Links: into Tier 1 -> into the perk; out of any tier -> out of the perk. Tier 1 > 2 > 3 links go away.
// needLv on a link = parent level the child needs; every link is Lv 1 (owning Lv 1 opens the next node).
import fs from "node:fs";

const here = new URL(".", import.meta.url);
const v3 = JSON.parse(fs.readFileSync(new URL("v3-export.json", here), "utf8"));
const wiki = JSON.parse(fs.readFileSync(new URL("perks-wiki.json", here), "utf8"));

const FOLLOW = new Set(["pn35_spe2", "pn39_dsmB2", "pn43_dsmC2", "pn49_dsmA3", "pn53_dsmB3", "pn57_spe3", "pn64_spe4", "pn71_dsmC3"]);
const gateShift = y => (y >= 2560 ? -480 : y >= 1880 ? -240 : 0);
const moveY = (id, y) => y + gateShift(y) + (FOLLOW.has(id) ? -240 : 0);

// Lv 3 text = effect + drawback ("However, ..." or ", but ...")
function splitDrawback(t) {
  const m = /^(.*?)(?:\.\s*However,\s*|,\s*but\s+)(.+)$/.exec(t);
  if (!m) return [t, ""];
  const fx = m[1].replace(/\s+$/, "") + ".";
  const d = m[2].replace(/\.?\s*$/, ".");
  return [fx, d[0].toUpperCase() + d.slice(1)];
}
const dot = t => t.replace(/\s+$/, "").replace(/([^.])$/, "$1.");

const famOf = n => (n.type === "tier" ? n.label.replace(/\s*Tier \d$/, "") : null);
const short = n => n.id.replace(/^pn\d+_/, "").replace(/\d$/, "");
const map = {}, nodes = [], perkIds = {};

for (const n of v3.nodes) {
  const fam = famOf(n);
  if (!fam) {
    nodes.push({ ...n, y: moveY(n.id, n.y) });
    map[n.id] = n.id;
    continue;
  }
  if (!perkIds[fam]) {
    const w = wiki[fam];
    if (!w) throw new Error("no wiki text for " + fam);
    const id = "pn_" + short(n);
    perkIds[fam] = id;
    const [fx3, drawback] = splitDrawback(w.lv[2]);
    nodes.push({
      id, label: fam, th: w.th, type: "perk", base: false, x: n.x, y: moveY(n.id, n.y),
      icon: n.icon, tag: w.tag, cooldown: w.cooldown, extras: {}, desc: "Perk",
      levels: [
        { lv: 1, cost: 1, fx: dot(w.lv[0]) },
        { lv: 2, cost: 1, fx: dot(w.lv[1]) },
        { lv: 3, cost: 1, fx: fx3, drawback }
      ]
    });
  }
  map[n.id] = perkIds[fam];
}

const seen = new Set(), edges = [];
for (const e of v3.edges) {
  const from = map[e.from], to = map[e.to];
  if (from === to || seen.has(from + ">" + to)) continue;
  seen.add(from + ">" + to);
  const ed = { id: e.id, from, to, style: e.style };
  if (e.hx != null) { ed.hx = e.hx; ed.hy = moveY("", e.hy); }
  ed.needLv = 1;
  edges.push(ed);
}

const out = `/* Skill tree v4 (one node per Perk, levels 1-3). Generated by tools/skilltree/build-v4.mjs from v3-export.json + perks-wiki.json. Do not edit by hand. */
window.MTX_TREE = ${JSON.stringify({ version: 4, nodes, edges })};
`;
fs.writeFileSync(new URL("../../mtx/js/skilltree-data.js", here), out);
console.log(`nodes ${nodes.length} (perks ${Object.keys(perkIds).length}), edges ${edges.length}`);
